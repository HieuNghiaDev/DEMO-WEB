export async function errorChecks(tab) {
  await tab.reload()
  const results = []
  for (const [error, expected] of [['preview:401', 'ログインの有効期限が切れています。再度ログインしてください。'], ['preview:403', 'この操作を行う権限がありません。管理者に確認してください。'], ['preview:404', '案件または資料が見つかりません。一覧を再読み込みしてください。'], ['preview:500', '資料収集データを取得・保存できませんでした。接続を確認して再試行してください。'], ['preview:network', '資料収集データを取得・保存できませんでした。接続を確認して再試行してください。']]) {
    await label(tab, '試験エラー').selectOption(error)
    await selectScenario(tab, 'uninitialized')
    await visible(tab, expected)
    assert.ok(!(await tab.playwright.domSnapshot()).includes('Never display this raw'))
    results.push(error)
  }
  await label(tab, '試験エラー').selectOption('')
  await selectScenario(tab, 'no-rules'); await tab.playwright.getByText('この事件類型には資料収集ルールが登録されていません。', { exact: true }).first().waitFor({ state: 'visible' })
  assert.equal(await button(tab, '資料収集リストを作成').count(), 0)
  await selectScenario(tab, 'missing-type'); await visible(tab, '事件類型が設定されていません。')
  assert.equal(await button(tab, '資料収集リストを作成').count(), 0)
  await selectScenario(tab, 'warnings'); await visible(tab, '旧書類データが含まれています。自動移行は行いません。')
  await rows(tab).first().waitFor({ state: 'visible' }); assert.equal(await rows(tab).count(), 3)
  return [...results, 'no rules', 'missing case type', 'coexistence warnings keep collection']
}

