// Repeatable integration checks using the supported Browser skill's existing tab.
// Run against /tests/fixtures/collection-api.html; all transport is isolated there.
import assert from 'node:assert/strict'
const button = (tab, name) => tab.playwright.getByRole('button', { name, exact: true })
const selectNames = ['試験シナリオ', '試験エラー', '応答時間', '確認目的', '取得要否', '取得作業', '確認', '担当者', '作業優先度', '内容充足', '結果・例外']
const label = (tab, name) => tab.playwright.getByRole(name === '閲覧のみ' ? 'checkbox' : selectNames.includes(name) ? 'combobox' : 'textbox', { name, exact: true })
const visible = async (tab, text) => tab.playwright.getByText(text, { exact: true }).waitFor({ state: 'visible' })
const logs = async tab => JSON.parse(await tab.playwright.getByTestId('transport-log').textContent())
const rows = tab => tab.playwright.getByRole('button', { name: /の詳細$/ })
const selectScenario = async (tab, value) => { await label(tab, '試験シナリオ').selectOption(value); await tab.playwright.domSnapshot() }

export async function initializationChecks(tab) {
  await tab.reload()
  await selectScenario(tab, 'uninitialized')
  await button(tab, '資料収集リストを作成').waitFor({ state: 'visible' })
  assert.ok((await tab.playwright.domSnapshot()).includes('3件'))
  assert.ok((await tab.playwright.domSnapshot()).includes('候補資料は自動的に「必要」には設定されません。'))
  assert.equal((await logs(tab)).filter(r => r.method === 'post').length, 0)
  await button(tab, '資料収集リストを作成').click()
  await tab.playwright.getByRole('dialog').waitFor({ state: 'visible' })
  await button(tab, 'キャンセル').click()
  assert.equal((await logs(tab)).filter(r => r.method === 'post').length, 0)
  await label(tab, '応答時間').selectOption('1200')
  await button(tab, '資料収集リストを作成').click()
  await button(tab, '作成する').click()
  assert.equal(await button(tab, '作成中…').isEnabled(), false)
  assert.equal(await button(tab, 'キャンセル').isEnabled(), false)
  await visible(tab, '3件の候補資料を作成しました。')
  await rows(tab).first().waitFor({ state: 'visible' })
  const requests = await logs(tab)
  const postIndex = requests.findIndex(r => r.method === 'post')
  assert.equal(requests.filter(r => r.method === 'post').length, 1)
  assert.equal(requests[postIndex].payload, undefined)
  assert.ok(requests.slice(postIndex + 1).some(r => r.url.endsWith('/initialization-preview')))
  assert.ok(requests.slice(postIndex + 1).some(r => r.url.endsWith('/document-collection')))
  assert.equal(await button(tab, '資料収集リストを作成').count(), 0)
  await label(tab, '応答時間').selectOption('25')
  await selectScenario(tab, 'new')
  await button(tab, '候補を追加').waitFor({ state: 'visible' })
  assert.equal(await rows(tab).count(), 3)
  await button(tab, '候補を追加').click(); await button(tab, '作成する').click()
  await visible(tab, '2件の候補資料を作成しました。')
  await button(tab, '候補を追加').waitFor({ state: 'detached' })
  await selectScenario(tab, 'noop'); await button(tab, '候補を追加').waitFor({ state: 'visible' })
  await button(tab, '候補を追加').click(); await button(tab, '作成する').click()
  await visible(tab, '追加する候補資料はありませんでした。最新の状態を表示します。')
  return ['initial candidate count/wording', 'cancel: no POST', 'confirm: empty POST + duplicate protection', 'success: preview/list refetched', 'no missing action hidden', 'new candidates preserve list', 'no-op truthful feedback']
}

